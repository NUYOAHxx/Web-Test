"""Generate a MoveIt-Setup-Assistant-style self-collision matrix (SRDF <disable_collisions>).

Same idea as MoveIt Setup Assistant: sample random configurations of the ACTIVE joints and disable
link pairs that are (a) adjacent in the kinematic tree, (b) rigidly attached (same moving body),
(c) in collision in the nominal pose ("Default"), (d) always in collision, (e) never in collision.
If you already have a MoveIt config for your robot, just point collision.srdf to its .srdf instead.

usage: python tools/gen_collision_srdf.py [--config config/g1.yaml] [--samples 10000]
"""
import argparse
import os
import sys
import time

import numpy as np
import pinocchio as pin

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from g1ik.config import load_config, rpath  # noqa
from g1ik.model import RobotModel  # noqa


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=None)
    ap.add_argument("--samples", type=int, default=10000)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    cfg = load_config(args.config)
    robot = RobotModel(cfg)
    m, gm = robot.model, robot.cmesh
    links = [m.frames[go.parentFrame].name for go in gm.geometryObjects]
    pj = [go.parentJoint for go in gm.geometryObjects]
    gm.removeAllCollisionPairs()
    pairs = []
    for i in range(len(links)):
        for k in range(i + 1, len(links)):
            if links[i] != links[k]:
                gm.addCollisionPair(pin.CollisionPair(i, k))
                pairs.append((i, k))
    gd = pin.GeometryData(gm)
    lp = sorted({tuple(sorted((links[i], links[k]))) for i, k in pairs})
    reason = {}
    # (a)/(b) adjacency & rigid attachment, using parent joints in the reduced model
    for i, k in pairs:
        key = tuple(sorted((links[i], links[k])))
        ji, jk = pj[i], pj[k]
        if ji == jk:
            reason[key] = "Rigid"  # never moves relative to each other (incl. locked legs/pelvis)
        elif m.parents[ji] == jk or m.parents[jk] == ji:
            reason.setdefault(key, "Adjacent")

    def colliding_link_pairs(q):
        pin.computeCollisions(m, robot.data, gm, gd, q, False)
        out = set()
        for (i, k), r in zip(pairs, gd.collisionResults):
            if r.isCollision():
                out.add(tuple(sorted((links[i], links[k]))))
        return out

    for key in colliding_link_pairs(robot.q_nominal):
        reason.setdefault(key, "Default")
    rng = np.random.default_rng(args.seed)
    count = {key: 0 for key in lp}
    t0 = time.time()
    for _ in range(args.samples):
        q = rng.uniform(robot.lower, robot.upper)
        for key in colliding_link_pairs(q):
            count[key] += 1
    dt = time.time() - t0
    for key in lp:
        if key in reason:
            continue
        if count[key] == 0:
            reason[key] = "Never"
        elif count[key] >= 0.95 * args.samples:
            reason[key] = "Always"
    out = rpath(cfg, cfg["collision"]["srdf"])
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write(f'<?xml version="1.0"?>\n<!-- generated by tools/gen_collision_srdf.py, {args.samples} samples -->\n')
        f.write(f'<robot name="{cfg["robot"]["name"]}">\n')
        for key in lp:
            if key in reason:
                f.write(f'  <disable_collisions link1="{key[0]}" link2="{key[1]}" reason="{reason[key]}"/>\n')
        f.write("</robot>\n")
    enabled = [k for k in lp if k not in reason]
    print(f"links with geometry: {len(set(links))}, link pairs: {len(lp)}, disabled: {len(reason)}, enabled: {len(enabled)}")
    from collections import Counter
    print("reasons:", Counter(reason.values()))
    print(f"sampling time: {dt:.1f}s for {args.samples} samples")
    for k in enabled:
        print("  enabled:", k, "hits", count[k])
    print("wrote", out)


if __name__ == "__main__":
    main()
